export function olxAdvertTone(status: string | null | undefined) {
  if (status === 'active') return 'ok'
  if (status === 'new' || status === 'unconfirmed') return 'info'
  if (status === 'limited' || status === 'unpaid' || status === 'disabled')
    return 'warn'
  if (
    status === 'blocked' ||
    status === 'moderated' ||
    status === 'removed_by_moderator'
  )
    return 'danger'
  return 'neutral'
}

